#!/bin/bash
# ite3_gpu/ext/build_specfem_asdf.sh -- build a SEPARATE SPECFEM3D 4.1.1 with
# ASDF support (--with-asdf) into specfem3d_asdf/ and bin_asdf/, leaving the
# production tree (specfem3d/, bin/) untouched. Mirrors 1_build_specfem_gpu.sh
# (same FC/MPI/CUDA/GENCODE handling) and adds:
#   --with-asdf ASDF_LIBS="-L<asdf>/lib -L<hdf5>/lib -Wl,-rpath,<hdf5>/lib"
# Prereqs (ext/README):  ext/hdf5  (parallel + Fortran, built vs the SYSTEM
# MPI)  and  ext/asdf  (asdf-library built vs ext/hdf5).
# Builds only the targets the NPROC=1 workflow uses (no xdecompose_mesh/Scotch,
# whose bundled Makefile is generated by an untracked step in the production tree).
# Usage: ext/build_specfem_asdf.sh [--check]
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/config.sh"; [[ -r "$ROOT/env.sh" ]] && source "$ROOT/env.sh"
STAGE=build_asdf; source "$ROOT/lib/common.sh"
SRC="$ROOT/specfem3d_asdf"; BIN="$ROOT/bin_asdf"
HDF5="${HDF5_ROOT:-$ROOT/ext/hdf5}"; ASDF="${ASDF_ROOT:-$ROOT/ext/asdf}"
[[ -x "$SRC/configure" ]] || die "no configure in $SRC (rsync the source tree first)"
[[ -f "$HDF5/lib/libhdf5.so" && -f "$HDF5/lib/libhdf5hl_fortran.so" ]] || die "parallel HDF5 with Fortran not found under $HDF5"
[[ -f "$ASDF/lib/libasdf.a" ]] || die "libasdf.a not found under $ASDF"
: "${CUDA_HOME:=/usr/local/cuda}"
GENCODE_OVERRIDE="-gencode=arch=compute_${GPU_ARCH},code=[sm_${GPU_ARCH},compute_${GPU_ARCH}]"
ASDF_LIBS="-L$ASDF/lib -L$HDF5/lib -Wl,-rpath,$HDF5/lib"
log "SRC=$SRC BIN=$BIN"; log "HDF5=$HDF5"; log "ASDF=$ASDF"; log "ASDF_LIBS=$ASDF_LIBS"; log "GENCODE=$GENCODE_OVERRIDE"
[[ "${1:-}" == "--check" ]] && exit 0
mkdir -p "$SRC/DATA" && cp "$ROOT/DATA/Par_file" "$SRC/DATA/Par_file"
cd "$SRC" || die "cd"
CONF_ARGS=( "FC=${FC:-gfortran}" "CC=${CC:-gcc}" "MPIFC=${MPIFC:-mpif90}" "MPICC=${MPICC:-mpicc}"
  "FLAGS_CHECK=${FLAGS_CHECK:--O3 -march=native -funroll-loops}" "CFLAGS=${CFLAGS_LOCAL:--O3 -march=native -funroll-loops}"
  --with-cuda=cuda12 "CUDA_INC=$CUDA_HOME/include" "CUDA_LIB=$CUDA_HOME/lib64"
  --with-asdf "ASDF_LIBS=$ASDF_LIBS" "CPPFLAGS=-I$ASDF/include -I$HDF5/include" )
log "configure ${CONF_ARGS[*]}"
./configure "${CONF_ARGS[@]}" > "$LOGDIR/configure_asdf.log" 2>&1 || { tail -30 "$LOGDIR/configure_asdf.log"; die "configure failed"; }
grep -qE '^[[:space:]]*NVCC[[:space:]]*=[[:space:]]*nvcc' Makefile || die "CUDA not enabled by configure"
grep -qE '^ASDF = yes' Makefile || die "ASDF not enabled by configure (Makefile has no 'ASDF = yes')"
log "configure OK: CUDA + ASDF enabled"
t0=$(date +%s)
make "GENCODE=$GENCODE_OVERRIDE" -j"$(nproc)" xgenerate_databases xspecfem3D xsmooth_sem xclip_sem xsum_preconditioned_kernels xsum_kernels xadd_model_iso xcombine_vol_data > "$LOGDIR/make_asdf.log" 2>&1 || { tail -40 "$LOGDIR/make_asdf.log"; die "make failed"; }
log "build OK in $(human_time $(( $(date +%s) - t0 )))"
mkdir -p "$BIN" && cp "$SRC"/bin/* "$BIN/"
for b in xspecfem3D xgenerate_databases; do [[ -x "$BIN/$b" ]] || die "missing $b"; done
log "linked libs of xspecfem3D:"; ldd "$BIN/xspecfem3D" | grep -E "hdf5|asdf|cudart" | tee -a "$LOGFILE"
log "DONE -> $BIN"
